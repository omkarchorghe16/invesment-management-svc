CREATE TABLE watchlist_items_usa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  watchlist_id BIGINT NOT NULL REFERENCES watchlists_usa(id) ON DELETE CASCADE,
  symbol VARCHAR(15) NOT NULL,
  name VARCHAR(160) NOT NULL,
  is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT watchlist_items_usa_watchlist_symbol_key UNIQUE (watchlist_id, symbol)
);

CREATE TABLE watchlist_items_india (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  watchlist_id BIGINT NOT NULL REFERENCES watchlists_india(id) ON DELETE CASCADE,
  symbol VARCHAR(15) NOT NULL,
  name VARCHAR(160) NOT NULL,
  is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT watchlist_items_india_watchlist_symbol_key UNIQUE (watchlist_id, symbol)
);

CREATE INDEX idx_watchlist_items_usa_watchlist ON watchlist_items_usa(watchlist_id);
CREATE INDEX idx_watchlist_items_india_watchlist ON watchlist_items_india(watchlist_id);

INSERT INTO watchlist_items_usa (id, watchlist_id, symbol, name, is_favorite)
SELECT item.id, item.watchlist_id, item.symbol, item.name, FALSE
FROM watchlist_items item
JOIN watchlists_usa watchlist ON watchlist.id = item.watchlist_id;

INSERT INTO watchlist_items_india (id, watchlist_id, symbol, name, is_favorite)
SELECT item.id, item.watchlist_id, item.symbol, item.name, FALSE
FROM watchlist_items item
JOIN watchlists_india watchlist ON watchlist.id = item.watchlist_id;

SELECT setval(
  pg_get_serial_sequence('watchlist_items_usa', 'id'),
  COALESCE(MAX(id), 0) + 1,
  FALSE
)
FROM watchlist_items_usa;

SELECT setval(
  pg_get_serial_sequence('watchlist_items_india', 'id'),
  COALESCE(MAX(id), 0) + 1,
  FALSE
)
FROM watchlist_items_india;

DROP TABLE watchlist_items;
